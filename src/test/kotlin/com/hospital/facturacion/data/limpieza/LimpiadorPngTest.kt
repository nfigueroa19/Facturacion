package com.hospital.facturacion.data.limpieza

import com.hospital.facturacion.ImagenesDePrueba
import com.hospital.facturacion.ImagenesDePrueba.chunkPng
import com.hospital.facturacion.contiene
import kotlin.test.Test
import kotlin.test.assertFalse
import kotlin.test.assertNotNull
import kotlin.test.assertNull
import kotlin.test.assertTrue

class LimpiadorPngTest {
    private val original = ImagenesDePrueba.png()
    private val iend = original.copyOfRange(original.size - 12, original.size)
    private val marcas = chunkPng("tEXt", "Software".toByteArray() + 0 + "Generated by AI".toByteArray()) +
        chunkPng("eXIf", "MM-autor".toByteArray()) + chunkPng("caBX", "c2pa-manifiesto".toByteArray())

    @Test
    fun `quita chunks de texto, EXIF, C2PA y datos anexados despues de IEND`() {
        val conMarcas = original.copyOfRange(0, original.size - 12) + marcas + iend + "OCULTO".toByteArray()
        val limpio = assertNotNull(LimpiadorPng().limpiar(conMarcas))
        listOf("Generated", "eXIf", "caBX", "c2pa", "OCULTO").forEach { assertFalse(limpio.contiene(it), it) }
        assertTrue(ImagenesDePrueba.decodificable(limpio))
    }

    @Test
    fun `rechaza un PNG truncado`() {
        assertNull(LimpiadorPng().limpiar(original.copyOfRange(0, original.size - 20)))
    }
}
