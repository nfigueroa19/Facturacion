package com.hospital.facturacion.data.limpieza

import com.hospital.facturacion.ImagenesDePrueba
import com.hospital.facturacion.ImagenesDePrueba.segmentoJpeg
import com.hospital.facturacion.contiene
import kotlin.test.Test
import kotlin.test.assertFalse
import kotlin.test.assertNotNull
import kotlin.test.assertNull
import kotlin.test.assertTrue

class LimpiadorJpegTest {
    private val original = ImagenesDePrueba.jpeg()
    private val marcas = segmentoJpeg(0xE1, "Exif".toByteArray() + 0 + 0 + "Generated by AI".toByteArray()) +
        segmentoJpeg(0xFE, "comentario del autor".toByteArray()) + segmentoJpeg(0xEB, "c2pa-jumb".toByteArray())

    @Test
    fun `quita EXIF, comentarios, C2PA y datos anexados despues de EOI`() {
        val conMarcas = original.copyOfRange(0, 2) + marcas + original.copyOfRange(2, original.size) + "OCULTO".toByteArray()
        val limpio = assertNotNull(LimpiadorJpeg().limpiar(conMarcas))
        listOf("Exif", "Generated", "comentario", "c2pa", "OCULTO").forEach { assertFalse(limpio.contiene(it), it) }
        assertTrue(limpio.contiene("JFIF"))
        assertTrue(ImagenesDePrueba.decodificable(limpio))
    }

    @Test
    fun `rechaza un JPEG truncado`() {
        assertNull(LimpiadorJpeg().limpiar(original.copyOfRange(0, original.size / 2)))
    }
}
